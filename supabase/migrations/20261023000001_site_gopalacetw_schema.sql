-- site_gopalacetw: 台灣宮廷藝術瓶 (WordPress + WooCommerce -> Supabase)
-- 只動 site_gopalacetw schema。保留舊站 WordPress ID（主鍵沿用 wp ID；新資料由 identity 從 1000000 起配號）與 slug。
-- 寫入一律經伺服器端 service role；anon/authenticated 只能讀已發布的公開內容。

-- ========== 共用 ==========
create or replace function site_gopalacetw.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end $$;

-- ========== 網站設定 ==========
create table if not exists site_gopalacetw.settings (
  key text primary key,
  value jsonb not null,
  is_public boolean not null default true,
  source text,                       -- 資料來源（wp rest root / html / features.json / pending_db）
  updated_at timestamptz not null default now()
);

-- ========== 作者 / 使用者（WP users；公開端點 404，先以被引用的 ID 建 placeholder） ==========
create table if not exists site_gopalacetw.authors (
  id bigint generated by default as identity (start with 1000000) primary key,  -- = wp_users.ID
  slug text unique,
  display_name text,
  email text,                        -- 私有，待 DB 匯入
  description text,
  avatar_url text,
  roles text[] not null default '{}',
  meta jsonb not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ========== 媒體 ==========
create table if not exists site_gopalacetw.media (
  id bigint generated by default as identity (start with 1000000) primary key,
  wp_id bigint unique,               -- wp attachment ID（html 掃描到但不在媒體庫的檔案為 null）
  slug text,
  title text,
  alt_text text,
  caption text,
  description text,
  mime_type text,
  original_path text not null,       -- 舊站 uploads/ 之後的路徑，如 2024/03/a.webp
  old_url text not null,             -- 舊站原檔網址
  storage_path text,                 -- bucket site-gopalacetw 內的物件路徑
  public_url text,                   -- 新網址
  canonical_media_id bigint references site_gopalacetw.media(id) on delete set null, -- 內容相同（sha1）時指向實際上傳的那筆
  width int, height int,
  bytes bigint,                      -- 上傳後大小
  original_bytes bigint,
  sha1 text,
  parent_post_id bigint,             -- wp post_parent（附件所屬文章/商品）
  author_id bigint,
  status text not null default 'publish',  -- publish / private（未公開附件，待 DB）
  source text not null default 'media_library',  -- media_library / html_scan / external / pending_db
  attachment_url text,               -- 舊附件頁網址（301 到檔案）
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
-- 媒體庫中有兩筆附件共用同一檔案（2024/04/mega-menu-image.webp、2024/03/article-thumb-8.webp），故 original_path 不設 unique
alter table site_gopalacetw.media drop constraint if exists media_original_path_key;
create index if not exists media_original_path_idx on site_gopalacetw.media(original_path);
create index if not exists media_canonical_idx on site_gopalacetw.media(canonical_media_id);
create index if not exists media_sha1_idx on site_gopalacetw.media(sha1);

-- 舊網址 → 新網址對照（含縮圖 -WxH、-scaled、外站鏡像、轉義網址等所有變體）
create table if not exists site_gopalacetw.media_url_map (
  old_url text primary key,
  new_url text not null,
  media_id bigint references site_gopalacetw.media(id) on delete set null,
  variant text not null default 'original', -- original / thumbnail / scaled / external / escaped / duplicate
  created_at timestamptz not null default now()
);
create index if not exists media_url_map_media_idx on site_gopalacetw.media_url_map(media_id);

-- ========== 分類／標籤（wp_terms + wp_term_taxonomy，含階層） ==========
create table if not exists site_gopalacetw.terms (
  id bigint generated by default as identity (start with 1000000) primary key,  -- = wp term_id
  taxonomy text not null,            -- category / post_tag / product_cat / product_tag / pa_<attribute>
  slug text not null,                -- 原始（可能為 percent-encoded）slug
  name text not null,
  description text not null default '',
  parent_id bigint references site_gopalacetw.terms(id) on delete set null,
  count int not null default 0,
  menu_order int not null default 0,
  image_media_id bigint references site_gopalacetw.media(id) on delete set null,
  display_type text,                 -- product_cat: default/products/subcategories/both
  meta jsonb not null default '{}',
  seo jsonb not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (taxonomy, slug)
);
create index if not exists terms_parent_idx on site_gopalacetw.terms(parent_id);
create index if not exists terms_image_idx on site_gopalacetw.terms(image_media_id);

-- ========== 文章／頁面／自訂文章類型（wp_posts） ==========
create table if not exists site_gopalacetw.posts (
  id bigint generated by default as identity (start with 1000000) primary key,  -- = wp post ID
  post_type text not null,           -- post / page / ct_content_block / wp_navigation / wp_block / ...
  slug text not null,                -- 原始 slug（可能 percent-encoded）
  status text not null default 'draft' check (status in ('publish','draft','pending','private','future','trash','inherit')),
  title text not null default '',
  content text not null default '',  -- 已改寫網址的 HTML
  excerpt text not null default '',
  author_id bigint references site_gopalacetw.authors(id) on delete set null,
  parent_id bigint references site_gopalacetw.posts(id) on delete set null,
  menu_order int not null default 0,
  featured_media_id bigint references site_gopalacetw.media(id) on delete set null,
  template text not null default '',
  comment_status text not null default 'closed',
  ping_status text not null default 'closed',
  password text,                     -- 受保護文章（私有）
  path text,                         -- 對外網址路徑（如 /home-2/）
  custom_css text,                   -- GreenShift _gspb_post_css（已改寫網址）
  meta jsonb not null default '{}',
  seo jsonb not null default '{}',   -- Rank Math / HTML head 擷取
  published_at timestamptz,
  modified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (post_type, slug)
);
create index if not exists posts_type_status_idx on site_gopalacetw.posts(post_type, status);
create index if not exists posts_author_idx on site_gopalacetw.posts(author_id);
create index if not exists posts_parent_idx on site_gopalacetw.posts(parent_id);
create index if not exists posts_featured_idx on site_gopalacetw.posts(featured_media_id);

create table if not exists site_gopalacetw.post_terms (
  post_id bigint not null references site_gopalacetw.posts(id) on delete cascade,
  term_id bigint not null references site_gopalacetw.terms(id) on delete cascade,
