-- ========== updated_at triggers ==========
do $$
declare t text;
begin
  foreach t in array array['settings','authors','media','terms','posts','comments','menus','products','product_variations',
    'customers','carts','cart_items','orders','coupons','discount_rules','forms','attributes'] loop
    execute format('drop trigger if exists touch_updated_at on site_gopalacetw.%I', t);
    execute format('create trigger touch_updated_at before update on site_gopalacetw.%I for each row execute function site_gopalacetw.touch_updated_at()', t);
  end loop;
end $$;

