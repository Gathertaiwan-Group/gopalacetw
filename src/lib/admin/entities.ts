// 後台／MCP 共用的資料表定義：欄位白名單、列表欄位、搜尋欄位（對齊 WordPress / WooCommerce 的意義）

export type FieldType =
  | "text"
  | "textarea"
  | "html" // 所見即所得
  | "number"
  | "money"
  | "bool"
  | "select"
  | "datetime"
  | "json"
  | "bigints" // bigint[]，以逗號分隔
  | "texts" // text[]，以逗號或換行分隔
  | "media" // media.id
  | "term"; // terms.id

export type Field = {
  name: string;
  label: string;
  type: FieldType;
  options?: string[];
  nullable?: boolean; // 空字串存 null
  readonly?: boolean;
  help?: string;
  taxonomy?: string;
};

export type EntityDef = {
  key: string;
  table: string;
  label: string;
  pk: string;
  pkType: "number" | "text" | "uuid";
  list: string[]; // 列表欄位
  search: string[]; // ilike 搜尋欄位
  order: [string, boolean]; // [欄位, ascending]
  fields: Field[];
  softDelete?: boolean; // 刪除時先移到 trash（status）
  revalidate?: boolean; // 寫入後更新前台快取
  readonly?: boolean;
  filters?: string[]; // 可用 ?<欄位>= 篩選
};

